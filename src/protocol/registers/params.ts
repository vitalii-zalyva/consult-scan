export const PARAM_BY_ID: ReadonlyMap<ParamId, ParamDef> = new Map(PARAMS.map((p) => [p.id, p]));

/** Looks up a param; throws for unknown ids (programming error). */
export function param(id: ParamId, list: readonly ParamDef[] = PARAMS): ParamDef {
  const p = list.find((x) => x.id === id);
  if (!p) throw new Error(`Unknown param ${id}`);
  return p;
}

export function registersOf(params: readonly ParamDef[]): number[] {
  return [...new Set(params.flatMap((p) => p.registers))].sort((a, b) => a - b);
}

/** Every distinct engine register address the app knows about. */
export const ALL_REGISTERS: readonly number[] = registersOf(PARAMS);

/** Params whose registers are all present in the supported set. */
export function paramsForRegisters(supported: ReadonlySet<number>, params: readonly ParamDef[] = PARAMS): ParamDef[] {
  return params.filter((p) => p.registers.every((r) => supported.has(r)));
}

/** XD-302: a raw param for an address that answers but is not in the map. */
export function undocumentedParam(register: number): ParamDef {
  const hex = register.toString(16).padStart(2, "0").toUpperCase();
  return def({
    id: `reg_${hex}`,
    label: `Register 0x${hex}`,
    fsmName: "undocumented",
    unit: "raw",
    group: "undocumented",
    registers: [register],
    decode: u8,
  });
}
